"""Build icons.js: an inline Lucide sprite (lucide-static 0.460.0, ISC licence).

Usage: python3 -I _icons.py /tmp/lucide-b/package/icons
Only the icons listed below are inlined; mockup pages use <svg class="i"><use href="#name"/></svg>.
"""
import re
import sys
from pathlib import Path

NAMES = """menu panel-left search chevron-down chevron-right chevron-up file-up files scan-text table-2
folder-output book-open settings circle-help undo-2 redo-2 scissors merge rotate-cw rotate-ccw trash-2
stamp filter triangle-alert circle-dashed circle-check eye locate-fixed qr-code x check minus plus
ellipsis signal-high signal-medium circle-x pencil square-dashed list-checks shuffle play maximize-2
arrow-up-down arrow-down check-check image zoom-in command arrow-down-to-line""".split()

src = Path(sys.argv[1])
out = []
for name in NAMES:
    svg = (src / f"{name}.svg").read_text()
    body = re.search(r">\s*(.*)</svg>", svg, re.S).group(1)
    body = re.sub(r"\s+", " ", body).strip()
    out.append(f'<symbol id="{name}" viewBox="0 0 24 24">{body}</symbol>')
sprite = "".join(out)
js = ("/* Lucide icons v0.460.0 (lucide-static), ISC licence, https://lucide.dev. Generated by _icons.py. */\n"
      "(function(){const s='" + sprite.replace("'", "\\'") + "';\n"
      "const d=document.createElement('div');d.style.display='none';"
      "d.innerHTML='<svg xmlns=\"http://www.w3.org/2000/svg\">'+s+'</svg>';"
      "document.body.prepend(d);})();\n")
Path(__file__).with_name("icons.js").write_text(js)
print(len(NAMES), "icons")
