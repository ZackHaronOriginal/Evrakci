"""Build icons.js: an inline SVG sprite of the Lucide icons these mockups use.

Lucide (lucide-static 0.460.0) is ISC licensed; the paths are copied verbatim.
Usage: python3 _icons.py /tmp/lucide-c/ex/package/icons
"""
import re
import sys
from pathlib import Path

NAMES = """menu undo-2 redo-2 scissors merge rotate-cw rotate-ccw trash-2 stamp filter triangle-alert
circle-dashed circle-check arrow-right-to-line eye search qr-code check x minus square chevron-right
chevron-down chevron-up table-2 play list-checks shuffle signal-high signal-medium circle-x pencil
square-dashed zoom-in zoom-out maximize-2 panel-right layout-grid command copy-minus scan-text
arrow-down-up check-check""".split()

src = Path(sys.argv[1])
out = ["// Generated by _icons.py from lucide-static@0.460.0 (ISC). Do not edit by hand.",
       "const LUCIDE = `<svg xmlns='http://www.w3.org/2000/svg' style='display:none'>"]
for n in NAMES:
    body = (src / f"{n}.svg").read_text()
    inner = re.search(r">\s*(.*)</svg>", body.split("<svg", 1)[1], re.S).group(1)
    inner = re.sub(r"\s+", " ", inner).strip()
    out.append(f"<symbol id='{n}' viewBox='0 0 24 24'>{inner}</symbol>")
out.append("</svg>`;")
out.append("document.body.insertAdjacentHTML('afterbegin', LUCIDE);")
Path(__file__).with_name("icons.js").write_text("\n".join(out) + "\n")
print(f"{len(NAMES)} icons")
