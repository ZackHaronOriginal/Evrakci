"""Regenerate src/evrakci/ui/lucide.py from an extracted lucide-static package.

    npm pack lucide-static@0.460.0 && tar xzf lucide-static-0.460.0.tgz
    python3 tools/build_lucide.py path/to/package

Each icon is the inner SVG markup of `icons/<source>.svg`; the first existing source wins, so
names that Lucide renamed later (funnel, help-circle) keep working across versions.
"""
